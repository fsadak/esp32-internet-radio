// Run from the project root: node design/fonts/generate-radio-fonts.cjs
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const root = path.resolve(__dirname, '../..');
const converter = path.join(root, '.tools/font-tools/node_modules/lv_font_conv');
const opentype = require(path.join(converter, 'node_modules/opentype.js'));
const source = path.join(root, '.pio/libdeps/esp32_radio/lvgl/scripts/generators/built_in_font/Montserrat-Medium.ttf');
const font = opentype.loadSync(source);
const requested = [];
for (let cp = 0xa0; cp <= 0x17f; ++cp) requested.push(cp);
requested.push(0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2026, 0x20ac, 0x20ba);
const supported = requested.filter(cp => font.charToGlyphIndex(String.fromCodePoint(cp)) !== 0);
const required = [...'ÇĞİÖŞÜçğıöşüÂÎÛâîûéÉäÄß“”’–—…'];
for (const letter of required) {
    if (!supported.includes(letter.codePointAt(0))) throw Error('Source font lacks ' + letter);
}
const symbols = String.fromCodePoint(...supported);
for (const size of [14, 18, 24, 28, 36]) {
    const output = path.join(root, `src/radio_turkish_${size}.c`);
    const args = [path.join(converter, 'lv_font_conv.js'), '--size', String(size), '--bpp', '4',
        '--format', 'lvgl', '--font', source, '--symbols', symbols, '--no-compress', '--no-kerning',
        '--lv-include', 'lvgl.h', '--lv-font-name', `radio_turkish_${size}`, '--output', output];
    const result = spawnSync(process.execPath, args, { encoding: 'utf8' });
    if (result.status !== 0) throw Error(result.stderr || result.stdout);
    // Keep generated headers reproducible and independent of local user paths.
    let text = fs.readFileSync(output, 'utf8');
    text = text.replace(/^ \* Opts:.*$/m,
        ' * Generated by design/fonts/generate-radio-fonts.cjs; Montserrat OFL license: design/fonts/Montserrat-OFL.txt');
    fs.writeFileSync(output, text, 'utf8');
    console.log(`${size}px: ${supported.length} additional glyphs`);
}
fs.writeFileSync(path.join(__dirname, 'radio-font-codepoints.json'), JSON.stringify({
    source: '.pio/libdeps/esp32_radio/lvgl/scripts/generators/built_in_font/Montserrat-Medium.ttf',
    converter: 'lv_font_conv 1.5.3', sizes: [14,18,24,28,36],
    supported, missing: requested.filter(cp => !supported.includes(cp))
}, null, 2) + '\n');
